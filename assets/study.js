const escapedTerms = keyTerms.map((term) => term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
const keyTermPattern = new RegExp(`\\b(${escapedTerms.join("|")})\\b`, "gi");
const minimalTermPattern = /\b(VOLTAGE|CURRENT|RESISTANCE|POLARITY|SEMICONDUCTOR)\b/gi;
const termPattern = document.body.dataset.highlighting === "minimal" ? minimalTermPattern : keyTermPattern;

if (levels.some((level) => deckByLevel.get(level).length !== expectedCardCounts.get(level))) {
  throw new Error("The card deck does not contain its expected number of cards.");
}

const state = { level: 1, session: null };

function hideAnswer() {
  elements.answer.hidden = true;
  elements.reveal.textContent = "Show answer";
  elements.reveal.setAttribute("aria-expanded", "false");
  elements.next.textContent = state.session.phase === "study" ? "Skip for review →" : "Skip card →";
  elements.next.setAttribute(
    "aria-label",
    state.session.phase === "study" ? "Skip this card and add it to the review pass" : "Skip this review card",
  );
}

function renderHighlightedText(element, text) {
  const fragment = document.createDocumentFragment();
  let previousIndex = 0;

  for (const match of text.matchAll(termPattern)) {
    fragment.append(text.slice(previousIndex, match.index));
    const term = document.createElement("strong");
    term.className = "key-term";
    term.textContent = match[0];
    fragment.append(term);
    previousIndex = match.index + match[0].length;
  }

  fragment.append(text.slice(previousIndex));
  element.replaceChildren(fragment);
}

function cardVisuals(card) {
  if (Array.isArray(card.visuals) && card.visuals.length > 0) return card.visuals.slice(0, 2);
  if (!card.imageUrl) return [];

  return [{
    type: "image",
    src: card.imageUrl,
    alt: card.imageAlt,
    caption: card.imageCaption ?? "Component image",
  }];
}

function renderVisuals(card) {
  const visuals = cardVisuals(card);
  elements.visuals.replaceChildren();
  elements.visuals.hidden = visuals.length === 0;

  for (const visual of visuals) {
    const figure = document.createElement("figure");
    figure.className = "prompt-visual";

    if (visual.type === "image") {
      const image = document.createElement("img");
      image.loading = "lazy";
      image.src = visual.src;
      image.alt = visual.alt ?? "Study prompt image";
      figure.append(image);
    } else {
      const diagram = document.createElement("pre");
      diagram.className = "prompt-diagram";
      diagram.setAttribute("role", "img");
      diagram.setAttribute("aria-label", visual.alt ?? visual.caption ?? "Study prompt diagram");
      diagram.textContent = visual.content;
      figure.append(diagram);
    }

    if (visual.caption) {
      const caption = document.createElement("figcaption");
      caption.textContent = visual.caption;
      figure.append(caption);
    }

    elements.visuals.append(figure);
  }
}

function renderCard(card) {
  state.current = card;
  elements.card.dataset.sessionComplete = "false";
  completion.hidden = true;
  elements.topic.textContent = card.topic;
  renderHighlightedText(elements.question, card.question);
  renderHighlightedText(elements.memorize, card.memorize);
  renderHighlightedText(elements.technical, card.technical);
  renderHighlightedText(elements.extra, card.extra);
  renderHighlightedText(elements.plain, card.plain);
  elements.docs.href = card.docsUrl;
  elements.docs.querySelector("span").textContent = `Read: ${card.docsLabel}`;
  renderVisuals(card);

  if (card.example) {
    elements.exampleCode.textContent = card.example;
    elements.example.hidden = false;
  } else {
    elements.exampleCode.textContent = "";
    elements.example.hidden = true;
  }

  const isReview = state.session.phase === "review";
  const activeCards = isReview ? state.session.reviewCards : state.session.studyCards;
  const position = state.session.position + 1;
  const phaseLabel = isReview ? "Review" : "Study";
  elements.position.textContent = `${phaseLabel} ${position} of ${activeCards.length}`;
  elements.count.textContent = `${activeCards.length - position} left in ${isReview ? "review" : "session"}`;
  hideAnswer();
  elements.status.textContent = `Level ${state.level}, ${phaseLabel.toLowerCase()} card ${position} of ${activeCards.length}: ${card.question}`;
}

function showCompletion({ focusRestart = true } = {}) {
  const reviewed = state.session.reviewCards.length;
  const mastered = state.session.studyCards.length - reviewed;
  const reviewSummary = reviewed === 0
    ? "You completed every card without adding one to review."
    : `${mastered} marked “Got it” · ${reviewed} reviewed once more.`;

  elements.card.dataset.sessionComplete = "true";
  completion.hidden = false;
  completionCopy.textContent = `${state.session.studyCards.length} cards complete. ${reviewSummary}`;
  elements.status.textContent = `Session complete. ${completionCopy.textContent}`;
  if (focusRestart) restart.focus();
}

function drawCurrentCard({ focusQuestion = true } = {}) {
  const card = currentCard(state.session);
  if (!card) {
    showCompletion({ focusRestart: focusQuestion });
    return;
  }

  renderCard(card);
  if (focusQuestion) elements.question.focus();
}

function startSession({ focusQuestion = true } = {}) {
  state.session = createStudySession(deckByLevel.get(state.level));
  drawCurrentCard({ focusQuestion });
}

function selectLevel(level) {
  state.level = level;
  buttons.forEach((button) => {
    const selected = Number(button.dataset.level) === level;
    button.setAttribute("aria-pressed", String(selected));
  });
  startSession();
}

function finishCurrent(outcome) {
  state.session = advanceSession(state.session, outcome);
  drawCurrentCard();
}

buttons.forEach((button) => {
  button.addEventListener("click", () => selectLevel(Number(button.dataset.level)));
});

elements.reveal.addEventListener("click", () => {
  if (elements.answer.hidden) {
    elements.answer.hidden = false;
    elements.reveal.textContent = state.session.phase === "study" ? "Got it" : "Done";
    elements.reveal.setAttribute("aria-expanded", "true");
    elements.next.textContent = state.session.phase === "study" ? "Review again ↻" : "Next review card →";
    elements.next.setAttribute(
      "aria-label",
      state.session.phase === "study" ? "Add this card to the review pass" : "Go to the next review card",
    );
    elements.status.textContent = "Answer shown. Choose how to continue.";
    return;
  }

  finishCurrent("got-it");
});

elements.next.addEventListener("click", () => finishCurrent("review"));

restart.addEventListener("click", () => startSession());

startSession({ focusQuestion: false });
